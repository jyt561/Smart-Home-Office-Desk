% BUILD_PACKAGE  One-command packaging script (requires MATLAB Compiler)
% Run inside MATLAB:  >> build_package
% Output: .\for_redistribution\MyAppInstaller_web.exe  (网络安装包)
%         .\for_redistribution_files\SmartDeskApp.exe  (绿色版,需目标机装 Runtime)

cd('D:\Matlab\work');

% Compile to standalone EXE + generate installer
% -m       : standalone application
% -o       : output exe name
% -R       : runtime flags
mcc('-m','SmartDeskApp.m', ...
    '-o','SmartDeskApp', ...
    '-R','-nodisplay', ...
    '-v');

fprintf('\n=== mcc done ===\n');

% Build the installer with bundled MATLAB Runtime choice
compiler.build.standaloneWindowsApplication( ...
    'SmartDeskApp.m', ...
    'AppName','AI Smart Desk System', ...
    'AuthorName','SmartDesk Pro', ...
    'Version','1.0.0', ...
    'OutputDirectory','D:\Matlab\work\package');

fprintf(['\n=== Package ready ===\n' ...
    'Installer : D:\Matlab\work\package\SmartDeskAppInstaller.exe\n' ...
    'Target machines need MATLAB Runtime R2026a ' ...
    '(installer can download it automatically).\n']);
